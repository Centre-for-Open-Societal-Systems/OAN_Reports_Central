def _w_chart(title, chart_type, label_field, value_fields, **extra):
    return {
        "id": f"w-{title.lower().replace(' ', '-')[:40]}",
        "type": "chart",
        "chart_type": chart_type,
        "title": title,
        "label_field": label_field,
        "value_fields": value_fields,
        "sort": extra.get("sort", "none"),
        "limit": extra.get("limit", 0),
        "stacked": extra.get("stacked", False),
    }


def _w_kpis(title, fields):
    return {
        "id": f"w-kpis-{title.lower().replace(' ', '-')[:32]}",
        "type": "kpis",
        "title": title,
        "kpi_fields": fields,
        "chart_type": "bar",
        "label_field": "",
        "value_fields": [],
        "sort": "none",
        "limit": 0,
        "stacked": False,
    }


def _w_table(title, columns):
    return {
        "id": f"w-table-{title.lower().replace(' ', '-')[:32]}",
        "type": "table",
        "title": title,
        "column_fields": columns,
        "chart_type": "bar",
        "label_field": "",
        "value_fields": [],
        "sort": "none",
        "limit": 0,
        "stacked": False,
    }


def _report(
    id,
    category,
    title,
    tag,
    frequency,
    description,
    *,
    chart_keys,
    upstream_service,
    widgets,
    field_mapping=None,
    category_kpi_chart_key="",
    api_endpoint="",
):
    primary = chart_keys[0] if chart_keys else ""
    endpoint = api_endpoint or (f"/api/v1/charts/{primary}" if primary else "")
    return {
        "id": id,
        "category": category,
        "title": title,
        "tag": tag,
        "frequency": frequency,
        "description": description,
        "is_system": True,
        "is_active": True,
        "is_customized": False,
        "source_type": "upstream",
        "chart_keys": chart_keys,
        "upstream_service": upstream_service,
        "api_endpoint": endpoint,
        "api_method": "GET",
        "data_path": "data",
        "field_mapping": field_mapping or {},
        "widgets": widgets,
        "category_kpi_chart_key": category_kpi_chart_key,
        "owner": "system",
    }


